// Engine functions that take an instance or a function as a plain int (`var int`): argument positions.
// Such arguments are pushed as PUSHI <symbol index>.
inline const std::unordered_map<std::string, std::vector<uint32_t>> InstanceAsInt = {
  {"NPC_KNOWSINFO",     {1}}, {"NPC_HASITEMS",      {1}}, {"MOB_HASITEMS", {1}}, {"HLP_ISITEM", {1}},
  {"CREATEINVITEMS",    {1}}, {"CREATEINVITEM",     {1}}, {"NPC_REMOVEINVITEMS", {1}},
  {"NPC_REMOVEINVITEM", {1}}, {"WLD_INSERTITEM",    {0}}, {"WLD_INSERTNPC", {0}}, {"HLP_GETNPC", {0}},
  {"INFO_ADDCHOICE",    {0,2}}, {"INFO_CLEARCHOICES", {0}}, {"NPC_HASITEMINSTANCE", {1}},
  {"NPC_GETINVITEM",    {1}},
  };

inline bool takesInstance(const std::string& fn, uint32_t arg) {
  auto it = InstanceAsInt.find(fn);
  if(it==InstanceAsInt.end())
    return false;
  for(auto i : it->second)
    if(i==arg)
      return true;
  return false;
  }

